"""Historical byte compatibility and unambiguous signed claims across record versions."""
import base64
import copy
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

from evidence import chain, extensions
from evidence.receipts import Keyring, sign_receipt, verify_receipt

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("canonical_offline_verifier", ROOT / "scripts/verify/receipt.py")
assert SPEC is not None and SPEC.loader is not None
OFFLINE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(OFFLINE)

FIELDS = {
    "id": "10000000-0000-0000-0000-000000000001",
    "tenant_id": "20000000-0000-0000-0000-000000000002",
    "principal_id": None, "request_id": "legacy-unicode", "action": "audit.read",
    "resource": "résumé/日本語", "outcome": "allow", "stage": "allow", "reason": "allowed",
    "policy_version": None, "input_sha256": None, "execution_id": None,
    "created_at": "2026-01-02T03:04:05.123456+05:30",
}
# Captured from the accepted predecessor, not generated by the implementation under test.
LEGACY_CANONICAL = (
    '{"action":"audit.read","created_at":"2026-01-01T21:34:05.123456Z","execution_id":null,'
    '"id":"10000000-0000-0000-0000-000000000001","input_sha256":null,"outcome":"allow",'
    '"policy_version":null,"principal_id":null,"reason":"allowed","request_id":"legacy-unicode",'
    '"resource":"résumé/日本語","stage":"allow","tenant_id":"20000000-0000-0000-0000-000000000002"}'
)
LEGACY_ROW_HASH = "ba8d3e85f25b26a266826051d4e5a15936700519354566bc1dfc3dd01425bf54"


def receipt(version=1):
    record = chain.decision_record(**FIELDS, record_version=version)
    previous = chain.genesis_hash(FIELDS["tenant_id"])
    link = {"position": 1, "prev_hash": previous, "row_hash": chain.compute_row_hash(record, previous)}
    decision = {**FIELDS, "tenant": {"id": FIELDS["tenant_id"], "slug": "fixture"}, "principal": None,
                "record_version": version, "extensions": {}}
    keyring = Keyring.generate()
    return {"decision": decision, "chain": link, **sign_receipt(keyring, record, link)}, keyring.public_map()


def verdicts(value, keys):
    online = {check.name: check.ok for check in verify_receipt(value, keys)}
    offline = {name: ok for name, ok, _ in OFFLINE.verify_receipt(value, keys)}
    assert online == offline
    return online


def test_legacy_unicode_timezone_and_row_hash_preserve_captured_bytes():
    record = chain.decision_record(**FIELDS)
    assert len(record) == 13 and "trace_id" not in record
    assert chain.canonical_json(record) == LEGACY_CANONICAL
    assert chain.compute_row_hash(record, chain.genesis_hash(FIELDS["tenant_id"])) == LEGACY_ROW_HASH
    assert chain.normalize_record({**record, "record_version": 1, "extensions": {}}) == record


@pytest.mark.parametrize("version", [1, 2])
def test_versions_verify_with_the_same_checks_online_and_offline(version):
    value, keys = receipt(version)
    assert all(verdicts(value, keys).values())
    signed = json.loads(value["canonical"])["decision"]
    assert ("record_version" in signed) is (version == 2)
    assert ("extensions" in signed) is (version == 2)
    if version == 1:
        del value["decision"]["record_version"]
        del value["decision"]["extensions"]
        assert all(verdicts(value, keys).values())


@pytest.mark.parametrize("version", [1, 2])
def test_extension_claim_cannot_reuse_a_valid_signature(version):
    value, keys = receipt(version)
    value["decision"]["extensions"] = {"model": {"provider": "unsigned-claim"}}
    checks = verdicts(value, keys)
    assert checks["signature"] is True
    assert checks["canonical"] is False and checks["row_hash"] is False


@pytest.mark.parametrize("version", [True, False, 1.0, 2.0, 0, 3, "2", None])
def test_unsupported_or_coerced_version_never_verifies(version):
    value, keys = receipt()
    value["decision"]["record_version"] = version
    assert not all(verdicts(value, keys).values())
    with pytest.raises(ValueError, match="version"):
        chain.decision_record(**FIELDS, record_version=version)


@pytest.mark.parametrize("value", [None, [], "", {"claim": True}])
def test_legacy_extensions_must_be_an_empty_object(value):
    candidate, keys = receipt()
    candidate["decision"]["extensions"] = value
    assert not all(verdicts(candidate, keys).values())


@pytest.mark.parametrize("number", [0.5, float("nan"), float("inf"), float("-inf")])
def test_nested_floats_are_refused_before_persistence(number):
    with pytest.raises(ValueError, match="integers"):
        extensions.validate_extensions({"sample": {"items": [1, {"score": number}]}})


def test_empty_registry_rejects_unknown_keys_and_nested_non_string_keys():
    with pytest.raises(ValueError, match="not registered"):
        extensions.validate_extensions({"unregistered": {"value": 1}})
    with pytest.raises(ValueError, match="keys must be strings"):
        extensions.validate_extensions({"unregistered": {1: "value"}})


@pytest.fixture
def sample_schema(monkeypatch):
    schema = {"type": "object", "properties": {"text": {"type": "string"}},
              "required": ["text"], "additionalProperties": False}
    monkeypatch.setattr(extensions, "EXTENSION_SCHEMAS", {"sample": schema})


def test_schema_validation_and_owned_result(sample_schema):
    source = {"sample": {"text": "original"}}
    owned = extensions.validate_extensions(source)
    source["sample"]["text"] = "changed"
    assert owned == {"sample": {"text": "original"}}
    for invalid in ({"text": 1}, {"text": "ok", "extra": True}):
        with pytest.raises(ValueError, match="schema"):
            extensions.validate_extensions({"sample": invalid})


def test_extension_order_does_not_change_hash(monkeypatch):
    monkeypatch.setattr(extensions, "EXTENSION_SCHEMAS", {
        "sample": {
            "type": "object",
            "properties": {"first": {"type": "string"}, "second": {"type": "integer"}},
            "required": ["first", "second"],
            "additionalProperties": False,
        },
    })
    first = chain.decision_record(**FIELDS, record_version=2, extensions={"sample": {"first": "a", "second": 2}})
    second = chain.decision_record(**FIELDS, record_version=2, extensions={"sample": {"second": 2, "first": "a"}})

    assert chain.compute_row_hash(first, "previous") == chain.compute_row_hash(second, "previous")


def test_size_limit_counts_canonical_utf8_bytes(sample_schema):
    overhead = len(chain.canonical_json({"sample": {"text": ""}}).encode("utf-8"))
    available = 4096 - overhead
    text = "é" * (available // 2) + "x" * (available % 2)
    value = {"sample": {"text": text}}
    assert len(chain.canonical_json(value).encode("utf-8")) == 4096
    assert extensions.validate_extensions(value) == value
    value["sample"]["text"] += "x"
    assert len(chain.canonical_json(value).encode("utf-8")) == 4097
    with pytest.raises(ValueError, match="byte limit"):
        extensions.validate_extensions(value)


def test_cycles_and_non_utf8_text_fail_as_validation_errors():
    cycle = {}
    cycle["self"] = cycle
    with pytest.raises(ValueError, match="cycles"):
        extensions.validate_extensions({"sample": cycle})
    with pytest.raises(ValueError, match="canonical JSON"):
        extensions.validate_extensions({"sample": "\ud800"})


def test_registered_schema_cannot_fetch_a_remote_reference(monkeypatch):
    monkeypatch.setattr(extensions, "EXTENSION_SCHEMAS", {"sample": {"$ref": "https://invalid.example/schema"}})
    with pytest.raises(ValueError, match="references"):
        extensions.validate_extensions({"sample": {}})


def test_mixed_chain_projects_versions_and_rejects_unsigned_export_claims():
    first = chain.decision_record(**FIELDS)
    second = chain.decision_record(**{**FIELDS, "id": "10000000-0000-0000-0000-000000000003"}, record_version=2)
    genesis = chain.genesis_hash(FIELDS["tenant_id"])
    first_hash = chain.compute_row_hash(first, genesis)
    second_hash = chain.compute_row_hash(second, first_hash)
    rows = [{"position": 1, "prev_hash": genesis, "row_hash": first_hash, "decision": first},
            {"position": 2, "prev_hash": first_hash, "row_hash": second_hash, "decision": second}]
    export = {"tenant_id": FIELDS["tenant_id"], "rows": rows, "checkpoints": []}
    assert all(ok for _, ok, _ in OFFLINE.verify_chain(export))
    online = [chain.ChainRow(r["position"], r["prev_hash"], r["row_hash"], r["decision"]) for r in rows]
    assert all(check.ok for check in chain.verify_chain(online, {0: genesis}))
    bad = copy.deepcopy(export)
    bad["rows"][0]["decision"]["extensions"] = {"claim": "not signed"}
    assert not all(ok for _, ok, _ in OFFLINE.verify_chain(bad))
    bad_online = [chain.ChainRow(r["position"], r["prev_hash"], r["row_hash"], r["decision"]) for r in bad["rows"]]
    assert not all(check.ok for check in chain.verify_chain(bad_online, {0: genesis}))


def test_malformed_hash_is_invalid_without_raising():
    value, keys = receipt(2)
    value["chain"]["prev_hash"] = "é" * 64
    checks = verdicts(value, keys)
    assert checks["canonical"] is False and checks["row_hash"] is False


@pytest.mark.parametrize("version", [1, 2])
def test_verifier_runs_standalone_and_rejects_unsigned_claims(version, tmp_path):
    value, keys = receipt(version)
    receipt_file, key_file = tmp_path / "receipt.json", tmp_path / "keys.json"
    key_file.write_text(json.dumps([
        {"key_id": key_id, "public_key": base64.b64encode(raw).decode("ascii")}
        for key_id, raw in keys.items()
    ]))
    command = [sys.executable, "-I", str(ROOT / "scripts/verify/receipt.py"), "receipt", str(receipt_file),
               "--keys", str(key_file)]
    receipt_file.write_text(json.dumps(value))
    good = subprocess.run(command, cwd=tmp_path, text=True, capture_output=True)
    assert good.returncode == 0 and good.stdout.strip().endswith("VALID"), good.stdout + good.stderr
    value["decision"]["extensions"] = {"model": {"provider": "unsigned-claim"}}
    receipt_file.write_text(json.dumps(value))
    bad = subprocess.run(command, cwd=tmp_path, text=True, capture_output=True)
    assert bad.returncode == 1 and bad.stdout.strip().endswith("INVALID"), bad.stdout + bad.stderr
