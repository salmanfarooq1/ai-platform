// Builds src/styles/tokens.css from tokens/tokens.json with Style Dictionary v4 (DTCG format).
// The groups `light` and `dark` are the two colour sets. Every other group is theme-free and goes in :root.
//
//   npm run tokens          write src/styles/tokens.css
//   npm run tokens:check    build to a temp folder and fail (exit 1) if src/styles/tokens.css differs: the drift check CI runs
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const OUT_DIR = CHECK ? fs.mkdtempSync(path.join(os.tmpdir(), 'tokens-')) : path.join(ROOT, 'src/styles')

function shadowCss(value) {
  const layers = Array.isArray(value) ? value : [value]
  return layers.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`).join(', ')
}

function cssValue(token) {
  const v = token.$value
  const type = token.$type
  if (type === 'fontFamily') return (Array.isArray(v) ? v : [v]).map((f) => (/[\s]/.test(f) ? `'${f}'` : f)).join(', ')
  if (type === 'cubicBezier') return `cubic-bezier(${v.join(', ')})`
  if (type === 'shadow') return shadowCss(v)
  const fluid = token.$extensions?.['gap.fluid']
  if (fluid) return `clamp(${fluid.min}, ${fluid.preferred}, ${v})`
  return String(v)
}

function entries(tokens) {
  return tokens.map((t) => ({ name: t.path.slice(t.path[0] === 'light' || t.path[0] === 'dark' ? 1 : 0).join('-'), value: cssValue(t) }))
}

function block(selector, list, indent = '') {
  const body = list.map((e) => `${indent}  --${e.name}: ${e.value};`).join('\n')
  return `${indent}${selector} {\n${body}\n${indent}}`
}

StyleDictionary.registerFormat({
  name: 'gap/css',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens
    const core = entries(all.filter((t) => t.path[0] !== 'light' && t.path[0] !== 'dark'))
    const light = entries(all.filter((t) => t.path[0] === 'light'))
    const dark = entries(all.filter((t) => t.path[0] === 'dark'))
    return [
      '/* Generated by Style Dictionary from ui/tokens/tokens.json. Do not edit by hand: run `npm run tokens`.',
      '   :root holds the theme-free tokens and the light set (the default).',
      '   Dark is layered on by the OS setting and re-asserted by [data-theme="dark"], so an explicit choice always wins.',
      '   [data-theme="light"] re-asserts light so it wins over a dark OS setting. */',
      '',
      block(':root', core),
      '',
      block(':root,\n[data-theme="light"]', [...light, { name: 'color-scheme-hint', value: 'light' }]).replace('  --color-scheme-hint: light;', '  color-scheme: light;'),
      '',
      '@media (prefers-color-scheme: dark) {',
      block(':root:not([data-theme="light"])', [...dark, { name: 'color-scheme-hint', value: 'dark' }], '  ').replace('--color-scheme-hint: dark;', 'color-scheme: dark;'),
      '}',
      '',
      block('[data-theme="dark"]', [...dark, { name: 'color-scheme-hint', value: 'dark' }]).replace('--color-scheme-hint: dark;', 'color-scheme: dark;'),
      '',
    ].join('\n')
  },
})

StyleDictionary.registerTransform({ name: 'name/gap-unique', type: 'name', transform: (t) => t.path.join('-') })

const sd = new StyleDictionary({
  usesDtcg: true,
  source: [path.join(ROOT, 'tokens/tokens.json')],
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    css: { transforms: ['name/gap-unique'], buildPath: `${OUT_DIR}/`, files: [{ destination: 'tokens.css', format: 'gap/css' }] },
  },
})
await sd.buildAllPlatforms()

if (CHECK) {
  const committed = fs.readFileSync(path.join(ROOT, 'src/styles/tokens.css'), 'utf8')
  const fresh = fs.readFileSync(path.join(OUT_DIR, 'tokens.css'), 'utf8')
  fs.rmSync(OUT_DIR, { recursive: true, force: true })
  if (committed !== fresh) {
    console.error('DRIFT: src/styles/tokens.css differs from what tokens/tokens.json generates. Run `npm run tokens` and commit the result.')
    process.exit(1)
  }
  console.log('No drift: src/styles/tokens.css is exactly what tokens/tokens.json generates.')
}
