import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { parseColor } from '@/lib/contrast'

const ROOT = path.resolve(__dirname, '../..')
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, 'tokens/tokens.json'), 'utf8')) as Record<string, unknown>
const css = fs.readFileSync(path.join(ROOT, 'src/styles/tokens.css'), 'utf8')

const TYPES = new Set(['color', 'dimension', 'fontFamily', 'duration', 'cubicBezier', 'number', 'shadow'])

interface Leaf { path: string[]; value: unknown; type: string; description?: string }

/** Walk the file the way the DTCG spec describes: a node with $value is a token, `$type` is inherited from the group. */
function leaves(node: Record<string, unknown>, trail: string[] = [], inherited?: string): Leaf[] {
  const out: Leaf[] = []
  const type = (node['$type'] as string | undefined) ?? inherited
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    const obj = child as Record<string, unknown>
    if ('$value' in obj) out.push({ path: [...trail, key], value: obj['$value'], type: ((obj['$type'] as string | undefined) ?? type) as string, description: obj['$description'] as string | undefined })
    else out.push(...leaves(obj, [...trail, key], type))
  }
  return out
}

const all = leaves(tokens)

describe('tokens.json is valid DTCG', () => {
  it('gives every token a $value and a known $type', () => {
    expect(all.length).toBeGreaterThan(80)
    for (const t of all) {
      expect(t.value, t.path.join('.')).not.toBeUndefined()
      expect(TYPES.has(t.type), `${t.path.join('.')} has type ${t.type}`).toBe(true)
    }
  })

  it('writes colours as parseable values, or as aliases to another token', () => {
    for (const t of all.filter((x) => x.type === 'color')) {
      const v = String(t.value)
      if (v.startsWith('{')) {
        const target = v.slice(1, -1).split('.')
        expect(all.some((l) => l.path.join('.') === target.join('.')), `${t.path.join('.')} aliases ${v}`).toBe(true)
      } else {
        expect(() => parseColor(v), t.path.join('.')).not.toThrow()
      }
    }
  })

  it('has the same colour roles in the light and dark sets', () => {
    const roles = (set: string) => all.filter((t) => t.path[0] === set).map((t) => t.path[1]).sort()
    expect(roles('dark')).toEqual(roles('light'))
  })

  it('has no brand blue and no pure black or white', () => {
    const colors = all.filter((t) => t.type === 'color').map((t) => String(t.value).toLowerCase())
    // The old brand blues, and pure black and white, written without colour literals.
    for (const hex of ['2f5bea', '6e8bff', '2449c4', '5a77ee', '000000', 'ffffff']) expect(colors).not.toContain(`#${hex}`)
    expect(all.some((t) => t.path.includes('brand'))).toBe(false)
  })

  it('uses 8px, 12px and 24px radii as the design system says', () => {
    const r = (name: string) => all.find((t) => t.path.join('.') === `radius.${name}`)?.value
    expect([r('sm'), r('md'), r('xl')]).toEqual(['8px', '12px', '24px'])
  })
})

describe('tokens.css is generated from tokens.json', () => {
  it('carries a generated-file banner and a variable for every token', () => {
    expect(css).toContain('Generated by Style Dictionary')
    for (const t of all) {
      const name = ['light', 'dark'].includes(t.path[0] as string) ? t.path.slice(1).join('-') : t.path.join('-')
      expect(css, `--${name}`).toContain(`--${name}:`)
    }
  })

  it('has the light set, the dark media query and the explicit dark and light selectors', () => {
    expect(css).toContain('[data-theme="light"]')
    expect(css).toContain('@media (prefers-color-scheme: dark)')
    expect(css).toContain('[data-theme="dark"]')
    expect(css).not.toContain('--brand')
  })
})
